const SV_VERB_DE = { äta:'essen', dricka:'trinken', skriva:'schreiben', läsa:'lesen', se:'sehen', gå:'gehen', komma:'kommen', göra:'machen', ta:'nehmen', köpa:'kaufen', träffa:'treffen', springa:'laufen, rennen', flyga:'fliegen', simma:'schwimmen', vinna:'gewinnen', glömma:'vergessen', ringa:'anrufen', hitta:'finden', sjunga:'singen', få:'bekommen; dürfen', sova:'schlafen', åka:'fahren' };
let GLOSS = { sv:{}, es:{} };
function buildGloss(){
  GLOSS = { sv:{}, es:{} };
  const put = (lang, form, lemma, de, gen) => {
    form = String(form || '').toLowerCase().trim();
    if (!form) return;
    const cur = GLOSS[lang][form];
    if (!cur) { GLOSS[lang][form] = { l:lemma && lemma.toLowerCase() !== form ? lemma : '', de, gen:!!gen }; return; }
    if (!(cur.gen && gen) || cur.de.includes(de)) return;
    if (lemma && cur.l && lemma !== cur.l) { cur.de = `${cur.l}: ${cur.de}; ${lemma}: ${de}`; cur.l = ''; cur.multi = true; }
    else if (cur.multi && lemma) cur.de += `; ${lemma}: ${de}`;
    else cur.de += '; ' + de;
  };
  ['sv', 'es'].forEach(lang => GLOSS_RAW[lang].split('\n').forEach(line => {
    const p = line.split('|');
    if (p.length === 3 && p[0].trim()) put(lang, p[0], p[1].trim(), p[2].trim());
  }));
  const art = { m:'der', f:'die', n:'das' };
  NOUNS.forEach(([de, g, dePl, sv, en, def, pl, defPl]) => {
    put('sv', sv, '', `${de} (${en}-Wort)`, true);
    put('sv', def, sv, `${art[g]} ${de}`, true);
    put('sv', pl, sv, `${dePl} (Plural)`, true);
    put('sv', defPl, sv, `die ${dePl}`, true);
  });
  Object.values(ADJS).forEach(([deBase, , forms, alts]) => [forms].concat(alts || []).forEach(f => {
    put('sv', f[0], '', deBase, true);
    put('sv', f[1], f[0], `${deBase} (bei ett-Wörtern)`, true);
    put('sv', f[2], f[0], f[3] ? `${deBase} (Plural)` : `${deBase} (Plural und bestimmte Form)`, true);
    if (f[3]) put('sv', f[3], f[0], `${deBase} (bestimmte Form)`, true);
    if (f[4]) put('sv', f[4], f[0], `${deBase} (Plural)`, true);
  }));
  VERBS_SV.forEach(v => {
    const de = SV_VERB_DE[v[0]] || '';
    put('sv', v[0], '', de, true);
    put('sv', v[1], v[0], `${de} (Präteritum)`, true);
    put('sv', v[2], v[0], `${de} (Supinum, mit har)`, true);
  });
  const adj = (m, f, de) => { put('es', m, '', de, true); put('es', f, m, de, true); put('es', plEs(m), m, `${de} (Plural)`, true); put('es', plEs(f), m, `${de} (Plural)`, true); };
  SE_STATE.concat(SE_CHAR).forEach(([m, f, de]) => adj(m, f, de));
  Object.keys(SE_RES_DE).forEach(m => adj(m, m.replace(/o$/, 'a'), SE_RES_DE[m]));
  SE_PROF.forEach(a => { put('es', a[0], '', a[4], true); put('es', a[1], a[0], a[5], true); put('es', a[2], a[0], a[6], true); put('es', a[3], a[0], a[7], true); });
  // Genus-Wörter, Zahlen, Uhrzeiten und Präsensformen automatisch aus den Daten der Übungsformen
  GENUS.sv.forEach(([w, g, de]) => put('sv', w, '', `${de} (${g}-Wort)`, true));
  GENUS.es.forEach(([w, g, de]) => put('es', w, '', `${de} (${g} ${w})`, true));
  for (let n = 13; n <= 99; n++) { put('sv', numWords('sv', n), '', String(n), true); }
  SV_UNITS.forEach((w, i) => { if (w) put('sv', w, '', String(i), true); }); SV_TENS.forEach((w, i) => { if (w) put('sv', w, '', String(i * 10), true); });
  Object.entries(ES_TEENS).forEach(([n, w]) => put('es', w, '', n, true)); ES_TENS.forEach((w, i) => { if (w) put('es', w, '', String(i * 10), true); }); ES_UNITS.forEach((w, i) => { if (w) put('es', w, '', String(i), true); });
  SV_H.forEach((w, i) => { if (i) put('sv', w, '', String(i), true); }); ES_H.forEach((w, i) => { if (i) put('es', w, '', String(i), true); });
  Object.entries(SV_PRES).forEach(([inf, pres]) => put('sv', pres, inf, `${SV_VERB_DE[inf] || ''} (Präsens)`, true));
  const PERS_DE = ['yo', 'tú', 'él, ella, usted', 'nosotros', 'ellos, ellas'];
  const TENSE_DE = { pres:'Präsens', indef:'Indefinido', imp:'Imperfecto', subj:'Subjuntivo' };
  const verbs = Object.keys(IRR_ES).map(v => [v, IRR_ES[v][0]]).concat(REG_ES);
  verbs.forEach(([inf, de]) => {
    put('es', inf, '', de, true);
    Object.keys(TENSE_DE).forEach(t => [0, 1, 2, 3, 4].forEach(i => put('es', conjugate(inf, t, i), inf, `${de} (${TENSE_DE[t]}, ${PERS_DE[i]})`, true)));
    put('es', participle(inf), inf, `${de} (Partizip)`, true);
  });
}
function lookupWord(lang, w){
  const k = String(w || '').toLowerCase().replace(/^[¿¡"„“«(]+|[.!?,;"„“”»)…]+$/g, '');
  return GLOSS[lang][k] || GLOSS[lang][k.replace(/:/g, '')] || null;
}
async function wiktionary(lang, w){
  const word = String(w).toLowerCase();
  const res = await fetch('https://en.wiktionary.org/api/rest_v1/page/definition/' + encodeURIComponent(word));
  if (!res.ok) throw new Error('http ' + res.status);
  const j = await res.json();
  const out = [];
  (j[lang] || []).forEach(e => (e.definitions || []).forEach(d => {
    const t = String(d.definition || '').replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim();
    if (t) out.push((e.partOfSpeech ? e.partOfSpeech + ': ' : '') + t);
  }));
  return out.slice(0, 4);
}
